#!/usr/bin/env python3
"""Render a Markdown time report from a collector snapshot."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


HOUR_MS = 3_600_000


def duration(ms: int) -> str:
    hours = ms / HOUR_MS
    if hours < 1:
        return f"{round(hours * 60)}m"
    return f"{hours:.1f}h"


def date_part(iso: str | None) -> str:
    return (iso or "unknown")[:10]


def total_line(name: str, ms: int) -> str:
    return f"| {name} | {duration(ms)} |"


def render(snapshot: dict[str, Any]) -> str:
    totals = snapshot["totals"]
    names = snapshot["project"]["names"]
    if not names:
        names = [Path(path).name for path in snapshot["project"]["directories"]]
    if not names:
        names = snapshot["project"]["project_ids"]
    scope = ", ".join(names) or "unknown project"
    period = f"{date_part(snapshot['range']['from'])} — {date_part(snapshot['range']['to'])}"
    lines = [
        "# Project time report",
        "",
        f"- **Project:** {scope}",
        f"- **Period:** {period}",
        f"- **Sessions:** {totals['sessions']} main, {totals['subagents']} subagents",
        f"- **Prompts / steps / tool calls:** {totals['prompts']} / {totals['steps']} / {totals['tool_calls']}",
        f"- **Tokens:** {totals['tokens_input']:,} in, {totals['tokens_output']:,} out, "
        f"{totals['tokens_reasoning']:,} reasoning, {totals['tokens_cache_read']:,} cache read",
        f"- **Cost:** ${totals['cost']:.4f}",
        "",
        "## Time summary",
        "",
        "| Metric | Value |",
        "| --- | ---: |",
        total_line("Execution (reconstructed)", totals["exec_ms"]),
        total_line("Last busy window", totals["busy_ms"]),
        "",
        "Execution time sums the intervals from the first assistant step to "
        "each `idle` message, so tool and shell waits are included. Last busy "
        "window reproduces `time_idle - time_busy` from `session_v2`, i.e. "
        "only the final execution of each session.",
        "",
        "## By day (UTC)",
        "",
        "| Day | Execution | Sessions | Prompts | Steps | Tool calls "
        "| Tokens in | Tokens out | Reasoning | Cache read |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for day in snapshot["days"]:
        lines.append(
            f"| {day['date']} | {duration(day['exec_ms'])} | {day['sessions']} | "
            f"{day.get('prompts', 0)} | {day.get('steps', 0)} | {day.get('tool_calls', 0)} | "
            f"{day.get('tokens_input', 0):,} | {day.get('tokens_output', 0):,} | "
            f"{day.get('tokens_reasoning', 0):,} | {day.get('tokens_cache_read', 0):,} |"
        )
    lines.extend([
        f"| Total | {duration(totals['exec_ms'])} | {totals['sessions'] + totals['subagents']} | "
        f"{totals['prompts']} | {totals['steps']} | {totals['tool_calls']} | "
        f"{totals['tokens_input']:,} | {totals['tokens_output']:,} | "
        f"{totals['tokens_reasoning']:,} | {totals['tokens_cache_read']:,} |",
        "",
        "Execution time is split at UTC midnight. Prompts, steps, tool calls, "
        "and tokens are attributed to the UTC day of the message that produced "
        "them; when a session's recorded token totals exceed the sum of its "
        "messages (for example an unfinished last step), the remainder is "
        "attributed to the session's creation day. Sessions counts sessions "
        "with activity on that day, so a session spanning midnight is counted "
        "on both days; the Total row shows unique sessions (main plus "
        "subagents).",
        "",
        "## Sessions",
        "",
        "| Created | Title | Type | Exec | Outcome |",
        "| --- | --- | --- | ---: | --- |",
    ])
    for session in snapshot["sessions"]:
        title = (session["title"] or "(untitled)").replace("|", "\\|")
        kind = "subagent" if session["subagent"] else "main"
        lines.append(
            f"| {date_part(session['created'])} | {title} | {kind} | "
            f"{duration(session['exec_ms'])} | {session['outcome'] or '-'} |"
        )
    lines.extend(["", "---", "", "Generated by `opencode-project-time`; source database was opened read-only.", ""])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("snapshot", type=Path, help="JSON snapshot from collect.py")
    parser.add_argument("--out", type=Path, required=True, help="Markdown report to write")
    args = parser.parse_args(argv)
    try:
        snapshot = json.loads(args.snapshot.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"report: cannot read snapshot: {exc}", file=sys.stderr)
        return 2
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(snapshot), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
